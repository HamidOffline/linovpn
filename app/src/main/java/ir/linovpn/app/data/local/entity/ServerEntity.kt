package ir.linovpn.app.data.local.entity

import androidx.room.Entity
import androidx.room.PrimaryKey
import ir.linovpn.app.domain.model.Server
import ir.linovpn.app.domain.model.ServerProtocol
import ir.linovpn.app.domain.model.VpnCore

@Entity(tableName = "servers")
data class ServerEntity(
    @PrimaryKey val id: String,
    val name: String,
    val host: String,
    val port: Int,
    val protocol: String,
    val preferredCore: String,
    val uuid: String?,
    val alterId: Int,
    val flow: String?,
    val network: String,
    val security: String,
    val serverName: String?,
    val publicKey: String?,
    val shortId: String?,
    val spiderX: String?,
    val fingerprint: String?,
    val path: String?,
    val hostHeader: String?,
    val serviceName: String?,
    val method: String?,
    val password: String?,
    val obfsType: String?,
    val obfsPassword: String?,
    val congestion: String?,
    val upMbps: Int,
    val downMbps: Int,
    val privateKey: String?,
    val peerPublicKey: String?,
    val localAddress: String, // comma-separated
    val username: String?,
    val profileId: String?,
    val latency: Long,
    val isSelected: Boolean,
    val isFavorite: Boolean,
    val rawUri: String?,
    val createdAt: Long
) {
    fun toDomain(): Server = Server(
        id = id,
        name = name,
        host = host,
        port = port,
        protocol = ServerProtocol.fromString(protocol),
        preferredCore = runCatching { VpnCore.valueOf(preferredCore) }.getOrDefault(VpnCore.XRAY),
        uuid = uuid,
        alterId = alterId,
        flow = flow,
        network = network,
        security = security,
        serverName = serverName,
        publicKey = publicKey,
        shortId = shortId,
        spiderX = spiderX,
        fingerprint = fingerprint,
        path = path,
        hostHeader = hostHeader,
        serviceName = serviceName,
        method = method,
        password = password,
        obfsType = obfsType,
        obfsPassword = obfsPassword,
        congestion = congestion ?: "bbr",
        upMbps = upMbps,
        downMbps = downMbps,
        privateKey = privateKey,
        peerPublicKey = peerPublicKey,
        localAddress = if (localAddress.isBlank()) emptyList() else localAddress.split(","),
        username = username,
        profileId = profileId,
        latency = latency,
        isSelected = isSelected,
        isFavorite = isFavorite,
        rawUri = rawUri,
        createdAt = createdAt
    )

    companion object {
        fun fromDomain(server: Server): ServerEntity = ServerEntity(
            id = server.id,
            name = server.name,
            host = server.host,
            port = server.port,
            protocol = server.protocol.name,
            preferredCore = server.preferredCore.name,
            uuid = server.uuid,
            alterId = server.alterId,
            flow = server.flow,
            network = server.network,
            security = server.security,
            serverName = server.serverName,
            publicKey = server.publicKey,
            shortId = server.shortId,
            spiderX = server.spiderX,
            fingerprint = server.fingerprint,
            path = server.path,
            hostHeader = server.hostHeader,
            serviceName = server.serviceName,
            method = server.method,
            password = server.password,
            obfsType = server.obfsType,
            obfsPassword = server.obfsPassword,
            congestion = server.congestion,
            upMbps = server.upMbps,
            downMbps = server.downMbps,
            privateKey = server.privateKey,
            peerPublicKey = server.peerPublicKey,
            localAddress = server.localAddress.joinToString(","),
            username = server.username,
            profileId = server.profileId,
            latency = server.latency,
            isSelected = server.isSelected,
            isFavorite = server.isFavorite,
            rawUri = server.rawUri,
            createdAt = server.createdAt
        )
    }
}
